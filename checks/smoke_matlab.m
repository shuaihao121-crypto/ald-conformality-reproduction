% Reproducibility smoke entry point for a clean MATLAB process or CI.
% This script runs only small structural checks; it never launches a full scan.
repository_root = fileparts(fileparts(mfilename('fullpath')));
addpath(repository_root);
smoke_report = ald_repro('smoke',struct('ExportFigures',false,'FigureVisible','off'));
assert(strcmp(smoke_report.status,'success'),'Smoke runner did not report success.');
assert(numel(smoke_report.sources)==21 && all([smoke_report.sources.matches_manifest]), ...
    'Preserved source hashes did not match the 21-file manifest.');
historical = aldrepro.historical(repository_root,false);
assert(isequal([historical.summary.pair_counts.penetration, ...
    historical.summary.pair_counts.slope,historical.summary.pair_counts.broadness],[26 26 24]), ...
    'Historical I-VII pair counts changed.');
means = historical.summary.mean_ratios;
assert(abs(means.B_over_A_penetration-1.4858283832)<1e-9 && ...
    abs(means.A_over_B_slope-1.9894567185)<1e-9 && ...
    abs(means.B_over_A_broadness-2.7564552931)<1e-9, ...
    'Historical I-VII ratio reconstruction changed.');
fprintf('Historical CSV checks passed; this did not rerun any research model.\n');
